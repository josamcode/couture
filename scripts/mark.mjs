// Brand mark + icons.
// Brand files live in public/brand/:
//   couture-ui-mark.svg              the monogram as a vector (FINAL file still to come from Jo)
//   couture-ui-mark-transparent.png  the monogram as a transparent PNG (received from Jo)
//   couture-ui-profile.png           1080×1080 profile picture on ink (received from Jo)
// What this script does:
// 1. If couture-ui-mark.svg is missing, writes a TEMPORARY vector redraw of the mark:
//    the Bodoni Moda "C" as an outline + the red dot, proportioned like Jo's PNG.
//    If couture-ui-profile.png is missing, writes a temporary profile picture.
//    Real files are never overwritten.
// 2. Regenerates favicon.svg (from the vector), favicon-32.png and apple-touch-icon.png
//    (from Jo's PNG when there is no final SVG).
// Run: npm run mark
import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import opentype from 'opentype.js';
import sharp from 'sharp';

const INK = '#0B0B0C';
const IVORY = '#F4F1EA';
const RED = '#A3122A';
const MARK = 'public/brand/couture-ui-mark.svg';
const PROFILE = 'public/brand/couture-ui-profile.png';

await mkdir('public/brand', { recursive: true });

function buildMark() {
  return readFile('node_modules/@fontsource/bodoni-moda/files/bodoni-moda-latin-400-normal.woff').then((buf) => {
    const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
    const size = 430;
    const glyph = font.charToGlyph('C');
    const adv = (glyph.advanceWidth / font.unitsPerEm) * size;
    const capH = ((font.tables.os2?.sCapHeight || 700) / font.unitsPerEm) * size;
    const dotR = capH * 0.093; // dot ≈ 19% of the cap height, as in Jo's mark
    const gap = capH * 0.02;
    const total = adv + gap + dotR * 2;
    const x = (512 - total) / 2;
    const baseline = (512 + capH) / 2;
    const d = font.getPath('C', x, baseline, size).toPathData(2);
    const cx = (x + adv + gap + dotR).toFixed(1);
    const cy = (baseline - dotR + capH * 0.01).toFixed(1);
    return (
      `<!-- TEMPORARY MARK generated by scripts/mark.mjs. Replace with the final couture-ui-mark.svg. -->\n` +
      `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" role="img" aria-label="Couture UI">` +
      `<path fill="${IVORY}" d="${d}"/><circle cx="${cx}" cy="${cy}" r="${dotR.toFixed(1)}" fill="${RED}"/></svg>\n`
    );
  });
}

let temporary = false;
if (!existsSync(MARK)) {
  await writeFile(MARK, await buildMark());
  temporary = true;
  console.log(`temporary mark written → ${MARK}`);
} else {
  console.log(`using existing mark → ${MARK}`);
}
const markSvg = await readFile(MARK, 'utf8');
const inner = markSvg.replace(/<!--[\s\S]*?-->/g, '').trim();
const innerB64 = Buffer.from(inner).toString('base64');

// Raster icons use Jo's transparent PNG unless a final (non-temporary) SVG exists.
const PNG_MARK = 'public/brand/couture-ui-mark-transparent.png';
const svgIsTemporary = markSvg.includes('TEMPORARY MARK');
const usePng = svgIsTemporary && existsSync(PNG_MARK);
if (svgIsTemporary) temporary = true;
const pngMark = usePng ? await sharp(PNG_MARK).trim().toBuffer() : null;
const pngTile = async (size, radius, pad) => {
  const box = size - pad * 2;
  const mark = await sharp(pngMark).resize(box, box, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } }).toBuffer();
  const bg = Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}"><rect width="${size}" height="${size}" rx="${radius}" fill="${INK}"/></svg>`);
  return sharp(bg).composite([{ input: mark, left: pad, top: pad }]).png().toBuffer();
};

// Square icon: ink tile with the mark centred.
const tile = (size, radius, pad) =>
  Buffer.from(
    `<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">` +
      `<rect width="${size}" height="${size}" rx="${radius}" fill="${INK}"/>` +
      `<image x="${pad}" y="${pad}" width="${size - pad * 2}" height="${size - pad * 2}" href="data:image/svg+xml;base64,${innerB64}"/></svg>`,
  );

if (!existsSync(PROFILE)) {
  await sharp(tile(1080, 0, 190)).png().toFile(PROFILE);
  temporary = true;
  console.log(`temporary profile written → ${PROFILE}`);
}

// favicon.svg must be self-contained (browsers do not load nested external images in favicons).
const viewBox = inner.match(/viewBox="([^"]+)"/)?.[1] ?? '0 0 512 512';
const body = inner.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
const [, , vw, vh] = viewBox.split(/\s+/).map(Number);
await writeFile(
  'public/favicon.svg',
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><rect width="64" height="64" rx="12" fill="${INK}"/>` +
    `<g transform="translate(6 6) scale(${(52 / vw).toFixed(5)} ${(52 / vh).toFixed(5)})">${body}</g></svg>\n`,
);
if (usePng) {
  await sharp(await pngTile(256, 48, 40)).resize(32, 32).png().toFile('public/favicon-32.png');
  await sharp(await pngTile(180, 0, 34)).png().toFile('public/apple-touch-icon.png');
} else {
  await sharp(tile(256, 48, 22)).resize(32, 32).png().toFile('public/favicon-32.png');
  await sharp(tile(180, 0, 26)).png().toFile('public/apple-touch-icon.png');
}
console.log(
  `icons written (favicon.svg, favicon-32.png, apple-touch-icon.png)` +
    (usePng ? ' — PNG icons from the supplied PNG mark' : '') +
    (temporary ? ' — the SVG mark is a TEMPORARY vector redraw' : ''),
);
