// Generates the torn-paper edge ONCE and writes it to src/data/torn.ts as a static asset.
// Seeded, so the same edge comes out every time. Change SEED to tear a different sheet.
// Run: npm run torn
import { writeFile } from 'node:fs/promises';

const SEED = 20261112;
const VB_W = 1600;
const VB_H = 120;

function mulberry32(a) {
  return () => {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const rnd = mulberry32(SEED);

// 1D value noise with smooth interpolation, summed over octaves.
function makeNoise() {
  const grid = Array.from({ length: 512 }, () => rnd() * 2 - 1);
  const at = (x) => {
    const i = Math.floor(x);
    const f = x - i;
    const u = f * f * (3 - 2 * f);
    const a = grid[((i % 512) + 512) % 512];
    const b = grid[(((i + 1) % 512) + 512) % 512];
    return a + (b - a) * u;
  };
  return (x, octaves, lacunarity = 2, gain = 0.5) => {
    let amp = 1;
    let freq = 1;
    let sum = 0;
    let norm = 0;
    for (let o = 0; o < octaves; o++) {
      sum += at(x * freq + o * 37.1) * amp;
      norm += amp;
      amp *= gain;
      freq *= lacunarity;
    }
    return sum / norm;
  };
}
const noise = makeNoise();

// A few larger "tears": places where the sheet ripped deeper or left a tongue of paper.
const tears = Array.from({ length: 7 }, () => ({
  x: rnd() * VB_W,
  w: 30 + rnd() * 90,
  d: (rnd() < 0.5 ? -1 : 1) * (10 + rnd() * 18),
}));
const tearAt = (x) =>
  tears.reduce((s, t) => {
    const k = (x - t.x) / t.w;
    return s + t.d * Math.exp(-k * k * 2.2);
  }, 0);

function profile(offsetY, rough, phase) {
  const pts = [];
  let x = 0;
  while (x < VB_W) {
    const big = noise(x / 260 + phase, 3) * 30; // slow drift of the tear line
    const mid = noise(x / 46 + phase * 3, 3) * 9; // hand-torn wobble
    const fine = noise(x / 7 + phase * 7, 2) * rough; // paper fibre
    const y = 58 + offsetY + big + mid + fine + tearAt(x) + (rnd() - 0.5) * rough * 0.8;
    pts.push([x, Math.min(VB_H - 14, Math.max(4, y))]);
    x += 3.5 + rnd() * 6.5; // irregular step = irregular facets
  }
  pts.push([VB_W, pts[pts.length - 1][1]]);
  return pts;
}

const toPath = (pts) =>
  `M0 ${VB_H}V${pts[0][1].toFixed(1)}` +
  pts
    .slice(1)
    .map(([x, y]) => `L${x.toFixed(1)} ${y.toFixed(1)}`)
    .join('') +
  `V${VB_H}Z`;

const main = toPath(profile(0, 4.2, 0));
// The fringe sits a little above the main edge: the thin, translucent lip of pulled paper fibre.
const fringe = toPath(profile(-9, 7.5, 11.3));

const out = `// GENERATED by scripts/torn.mjs (seed ${SEED}). Static asset: do not edit by hand, re-run the script instead.
export const TORN_VIEWBOX = { width: ${VB_W}, height: ${VB_H} } as const;
export const TORN_MAIN = '${main}';
export const TORN_FRINGE = '${fringe}';
`;
await writeFile('src/data/torn.ts', out);
console.log(`torn edge written: main ${main.length} chars, fringe ${fringe.length} chars`);
