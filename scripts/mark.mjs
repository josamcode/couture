// Brand mark + icons.
// 1. If public/brand/couture-ui-mark.svg is missing, writes a TEMPORARY mark:
//    the Bodoni Moda "C" (converted to an outline, so it needs no font) + the red dot.
//    If public/brand/couture-ui-profile.png is missing, writes a temporary 1080×1080 profile on ink.
//    Jo's real files are never overwritten.
// 2. Always regenerates favicon.svg, favicon-32.png and apple-touch-icon.png from the mark.
// Run: npm run mark
import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import opentype from 'opentype.js';
import sharp from 'sharp';

const INK = '#0B0B0C';
const IVORY = '#F4F1EA';
const RED = '#A3122A';
const MARK = 'public/brand/couture-ui-mark.svg';
const PROFILE = 'public/brand/couture-ui-profile.png';

await mkdir('public/brand', { recursive: true });

function buildMark() {
  return readFile('node_modules/@fontsource/bodoni-moda/files/bodoni-moda-latin-400-normal.woff').then((buf) => {
    const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
    const size = 430;
    const glyph = font.charToGlyph('C');
    const adv = (glyph.advanceWidth / font.unitsPerEm) * size;
    const capH = ((font.tables.os2?.sCapHeight || 700) / font.unitsPerEm) * size;
    const dotR = 24;
    const gap = 10;
    const total = adv + gap + dotR * 2;
    const x = (512 - total) / 2;
    const baseline = (512 + capH) / 2;
    const d = font.getPath('C', x, baseline, size).toPathData(2);
    const cx = (x + adv + gap + dotR).toFixed(1);
    const cy = (baseline - dotR).toFixed(1);
    return (
      `<!-- TEMPORARY MARK generated by scripts/mark.mjs. Replace with the final couture-ui-mark.svg. -->\n` +
      `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" role="img" aria-label="Couture UI">` +
      `<path fill="${IVORY}" d="${d}"/><circle cx="${cx}" cy="${cy}" r="${dotR}" fill="${RED}"/></svg>\n`
    );
  });
}

let temporary = false;
if (!existsSync(MARK)) {
  await writeFile(MARK, await buildMark());
  temporary = true;
  console.log(`temporary mark written → ${MARK}`);
} else {
  console.log(`using existing mark → ${MARK}`);
}
const markSvg = await readFile(MARK, 'utf8');
const inner = markSvg.replace(/<!--[\s\S]*?-->/g, '').trim();
const innerB64 = Buffer.from(inner).toString('base64');

// Square icon: ink tile with the mark centred.
const tile = (size, radius, pad) =>
  Buffer.from(
    `<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">` +
      `<rect width="${size}" height="${size}" rx="${radius}" fill="${INK}"/>` +
      `<image x="${pad}" y="${pad}" width="${size - pad * 2}" height="${size - pad * 2}" href="data:image/svg+xml;base64,${innerB64}"/></svg>`,
  );

if (!existsSync(PROFILE)) {
  await sharp(tile(1080, 0, 190)).png().toFile(PROFILE);
  temporary = true;
  console.log(`temporary profile written → ${PROFILE}`);
}

// favicon.svg must be self-contained (browsers do not load nested external images in favicons).
const viewBox = inner.match(/viewBox="([^"]+)"/)?.[1] ?? '0 0 512 512';
const body = inner.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
const [, , vw, vh] = viewBox.split(/\s+/).map(Number);
await writeFile(
  'public/favicon.svg',
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><rect width="64" height="64" rx="12" fill="${INK}"/>` +
    `<g transform="translate(6 6) scale(${(52 / vw).toFixed(5)} ${(52 / vh).toFixed(5)})">${body}</g></svg>\n`,
);
await sharp(tile(256, 48, 22)).resize(32, 32).png().toFile('public/favicon-32.png');
await sharp(tile(180, 0, 26)).png().toFile('public/apple-touch-icon.png');
console.log(`icons written (favicon.svg, favicon-32.png, apple-touch-icon.png)${temporary ? ' — from TEMPORARY brand files' : ''}`);
